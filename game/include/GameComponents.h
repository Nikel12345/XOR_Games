#include "ComponentSerializer.h"

struct MassComponent {
    float mass = 1.0f;
};

// Источник гравитации: центральное тело, к которому притягиваются сущности со скоростью.
// Центр НЕ константа в игровом коде — это ПОЗИЦИЯ самой сущности (трансляция её Positions),
// а сила — поле gm. Отсюда следует всё остальное: центров может быть несколько (ускорения
// складываются), центр видно в редакторе и можно двигать гизмо, а сохранение/загрузка сцены
// его переносят как обычную сущность.
//
// gm = G·M (μ, стандартный гравитационный параметр). ОБЯЗАН совпадать с GM в
// scripts/scene_gen/scene_gen.py: круговые скорости кубам раздаёт генератор по sqrt(GM/r),
// при другом gm орбиты станут эллиптичными/раскрутятся. Форму орбиты задаёт ТОЛЬКО gm.
//
// id — ключ центра, на который ссылаются его джеты (JetComponent::center). Ключ, а не id
// сущности: ссылки на сущности загрузчик сцены переводит в новые id только у ParentComponent,
// а число переживает сохранение/загрузку как есть. Разные центры обязаны иметь разные id.
//
// core_radius — центр как однородный шар этого радиуса: внутри него ускорение gm*r/R^3, линейно
// по r, и период обращения одинаков на любом радиусе — диск внутри вращается колесом, спиральные
// рукава не закручиваются (scene_gen2.py). Снаружи — обычное gm/r^2. 0 = точечная масса.
struct GravityComponent {
    float    gm = 5000.0f;
    uint32_t id = 0;
    float    core_radius = 0.0f;
};

// Куб джета: вылетает из своего центра и летит по прямой — гравитация его не тянет. Ушедший от
// центра дальше GravityWorldComponent::jet_return_distance возвращается в центр с той же скоростью, поэтому
// направление и темп струи задаёт только стартовая скорость из генератора (scene_gen2.py).
// center — GravityComponent::id центра. Центра с таким id в сцене нет — куб не возвращается.
struct JetComponent {
    uint32_t center = 0;
};

// sim_dt — «скорость времени»: не влияет на форму орбиты, только на темп. У движка нет
// delta-time (камера/свет — тоже по кадрам), поэтому шаг фиксированный. При радиусах 50..350
// орбиты долгие — увеличивай sim_dt (или уменьшай радиусы диска в scene_gen.py), чтобы вращение
// было заметным; слишком большой шаг добавит прецессию/дрожание орбиты.
struct GravityWorldComponent {
    float sim_dt = 0.05f;
    float jet_return_distance = 2500.0f;
};

struct GravitationalLensComponent {
    float schwarzschild_radius = 10.0f;
    float inner_radius = 0.0f;
};

