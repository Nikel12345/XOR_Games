#pragma once
#include <cstdint>
#include <vector>
#include <glm/glm.hpp>
#include <glm/gtc/quaternion.hpp>
class EngineContext;
class CameraManager;

// Набор фрактальных апдейтеров игры — зеркало движкового DefaultUpdateSet: каждая Set*Updater
// вешает CreateUpdateInstruction на СВОЙ именованный буфер, а сами буферы создаёт MyGame::MainInit
// (CreateBufferData) под if'ом с именем сцены — там же выбирается и апдейтер. Рендер-ресурсы
// (модель/шейдеры/sp/материал) — ресурсы СЦЕНЫ (saved_scene/<имя>), энтити фона — в её scene.json.
//
// ТРЮК С КАМЕРОЙ (общий для всех фракталов). Камера движка — чистый АККУМУЛЯТОР сдвига в
// игровых юнитах: каждый тик апдейтер забирает GetPosition() как дельту и сбрасывает её в ноль,
// поэтому дельта всегда ~O(1) — полное разрешение float на любой скорости и глубине. Позиция во
// фрактале — собственное состояние апдейтера (double и точнее), масштаб применяется при
// внесении дельты. В шейдер из камеры доезжает максимум ротация (v_dir у 3D); у 2D — ничего.
//
// ГУБКА МЕНГЕРА (scene_fractal): позиция = целочисленный base-3 адрес ячейки + double-локаль
// + дробный масштаб σ; авто-масштаб следует за CPU-зеркалом DE губки. Подробности — у
// SetMengerFrameUpdater в cpp.
//
// МАНДЕЛЬБРОТ (scene_mandelbrot): центр окна — double (резкость ~50 октав, как и у орбиты),
// зум half_h — ПОЛНОСТЬЮ РУЧНОЙ (I/K, без авто-слежения: у тонких нитей множества DE
// проваливается на порядки ниже видимого масштаба и авто-цель утаскивала камеру в точку без
// возможности отдалить — см. FractalUpdateSet.cpp). Каждый тик CPU итерирует РЕФЕРЕНС-орбиту
// центра в double и публикует её буфером; пиксели в шейдере итерируют только дельту
// (перетурбация, ре-базирование Чжуорана).
namespace FractalUpdateSet
{
    // Имена буферов. На них по имени ссылаются fs_buffers sp сцены (shaders.json) — буфер
    // ДОЛЖЕН существовать до LoadScene (резолв имён идёт по уже созданным, Engine_Scene).
    inline constexpr const char* MENGER_FRAME_BUFFER     = "FractalFrameBuffer";
    inline constexpr const char* MANDELBROT_ORBIT_BUFFER = "MandelbrotOrbitBuffer";

    // Кадр губки: [0]=(позиция,глубина), [1]=(K,tFar,1/туман,0), [2+j]=(офсет предка, 3^(j+1)).
    inline constexpr uint32_t MENGER_MAX_CONTEXT = 8;   // уровней предков в шейдер (дальше — туман)
    inline constexpr uint32_t MENGER_FRAME_BYTES = (2 + MENGER_MAX_CONTEXT) * 4 * sizeof(float);

    // Кадр Мандельброта: float2-записи — [0]=(len asuint, half_h), [1]=(aspect, 0), [2+n]=Z_n.
    // 4096 итераций референса хватает на весь запас резкости double (~50 октав: 64+96/октаву).
    inline constexpr uint32_t MANDELBROT_ORBIT_MAX   = 4096;
    inline constexpr uint32_t MANDELBROT_ORBIT_BYTES = (2 + MANDELBROT_ORBIT_MAX) * 2 * sizeof(float);

    // Позиция во фрактале-губке: целочисленный base-3 адрес якорной ячейки (цифры {0,1,2} по
    // осям, root-first) + double-локаль в юнитах ячейки ([-1,1] внутри) + дробный масштаб σ
    // (мировой размер s = σ·3^-depth). Точность НЕ зависит от глубины: адрес — точная целая
    // арифметика, локаль всегда ~O(1). Камера — первый экземпляр (внутри апдейтера губки);
    // якоря объектов (этапы 3-4 переноса объектов во фрактал) — следующие.
    struct FractalPos {
        std::vector<glm::ivec3> addr;
        glm::dvec3 local{ 0.0 };
        double     sigma = 1.0;
    };

    // Разность позиций: точка A относительно точки B в юнитах якорной ячейки B (это готовая
    // трансляция для камерно-относительной матрицы объекта). Общий префикс адресов сокращается
    // в ЦЕЛЫХ до любых float-вычислений: double точен, пока расхождение адресов <= ~33 уровней
    // (2·3^33 < 2^53); дальше относительная ошибка ~1e-16 на величине, уходящей в отсев/туман.
    //
    // ВАЖНО: σ владельца точки B (камеры) НЕ входит ни в offset, ни в scale. Кадр рендера —
    // юниты якорной ЯЧЕЙКИ, и картинка рэймарчера от σ не зависит (σ — это «размер
    // наблюдателя»: скорость движения и дальность тумана, а не геометрия кадра). Деление на
    // σ камеры заставляло объект «дышать» относительно фрактала при работе авто-масштаба.
    struct FractalOffset {
        glm::dvec3 offset;   // A − B, юниты ячейки якоря B
        double     scale;    // юнит объекта A → юниты якоря B: σ_A·3^{d_B − d_A}
    };
    FractalOffset DiffFractalPos(const FractalPos& a, const FractalPos& b);

    // Тик позиции/масштаба губки: снять дельту камеры-аккумулятора, боковые переносы адреса,
    // потолок глубины, авто-масштаб с оболочкой у стенки, ренормализация σ. Вызывать из
    // MainIterate КАЖДЫЙ тик (после внесения ввода в камеру, ДО prepare) — тогда трансформы
    // якорённых объектов, посчитанные следом от MengerCameraPos(), уезжают на GPU в ТОМ ЖЕ
    // тике, что и кадр фрактала (штатный StoreTransforms идёт в prepare ПОСЛЕ MainIterate),
    // и позиция камеры обнуляется ДО снапшота view — в cameraBuffer всегда чистая ротация.
    // Публикация кадра в буфер осталась в апдейтере (SetMengerFrameUpdater) — он теперь
    // только сериализует состояние.
    void MengerTick(CameraManager* cm);

    // Текущая позиция камеры губки — точка отсчёта для DiffFractalPos якорённых объектов.
    const FractalPos& MengerCameraPos();

    // Дальность насыщения тумана ТЕКУЩЕГО кадра губки, в юнитах якоря камеры (= tFar шейдера,
    // FOG_DIST·σ ≤ 7500). Дальше неё не видно ничего — граница отсева якорённых объектов.
    double MengerFogFar();

    // ЛИЧНАЯ логика масштаба объекта («куб — мини-камера», этап 8b): DE губки в точке позиции
    // → σ-цель из посадки тела в зазор (радиус тела σ·body_radius = OBJ_FIT·DE), сглаживание
    // в лог-пространстве (те же пороги, что у камеры) + собственная нормализация: боковые
    // переносы адреса, потолок глубины от адреса (фантомное окно K предков), σ→[1,3)
    // переносом уровня — объект «сам считает свои пересечения масштабов». Размер зависит
    // ТОЛЬКО от окружения его точки, не от камеры.
    // body_radius — радиус тела в ЮНИТАХ МОДЕЛИ (из bound-сфер сабмешей: max(|центр|+радиус);
    // у куба полу-размера 1 это √3 — прежнее поведение). Юзерский model_scale сюда НЕ входит:
    // намеренное растяжение гизмо правило душить не должно.
    // Звать каждый тик для КАЖДОГО якорёного объекта (общий контур MainIterate, после съёма
    // правки гизмо — тот интерпретирует дельты в σ прошлой записи). В сошедшемся состоянии
    // шаг exp(≈0) — дрейфа нет; попутно держит состояние каноничным. Вызывать с sim-потока.
    void MengerObjectScaleTick(FractalPos& p, double body_radius);

    // ECS-компонент якоря (этап 4): фрактальная позиция объекта — ЕДИНСТВЕННЫЙ источник
    // истины, Positions лишь её камерно-относительная проекция на тик. Движок pos не трогает;
    // меняет её только съём правки гизмо (этап 7, см. ниже). local МОЖЕТ выходить за [-1,1]:
    // точка живёт в юнитах своей якорной ячейки, спавн-смещение вперёд от камеры остаётся
    // ~O(σ), и DiffFractalPos переваривает любой local — нормализация адреса не нужна.
    // Сериалайзера нет: спавн-кубы несут GeneratedComponent (SaveScene их пропускает).
    struct FractalAnchorComponent {
        FractalPos pos;
        // Ориентация и пер-осевой масштаб (этап 8) — С АДРЕСНОЙ МАТЕМАТИКОЙ НЕ ВЗАИМОДЕЙСТВУЮТ:
        // кадр рендера всегда сонаправлен осям якоря (ребейзы/переносы ориентацию не трогают),
        // поэтому rot — абсолютная мировая ориентация, model_scale — безразмерный множитель
        // ~O(1) поверх фрактального масштаба (полный пер-осевой масштаб = off.scale·model_scale).
        // Матрица контура = T·R·S.
        glm::quat  rot{ 1.0f, 0.0f, 0.0f, 0.0f };
        glm::dvec3 model_scale{ 1.0 };
        // Кэш матрицы, записанной ForEach-контуром в ПРОШЛЫЙ тик (этапы 7-8 — правка гизмо):
        // линейная часть (столбцы) + трансляция + фрактальный масштаб записи. Расхождение
        // Positions с кэшем в начале контура = внешняя правка (SetTransformCmd гизмо
        // исполняется в ExecuteCommands ДО контура): дельта трансляции → в локаль якоря
        // (юниты камеры → юниты объекта через written_fs), линейная часть — АБСОЛЮТОМ:
        // нормы столбцов/written_fs → model_scale, нормированные столбцы → rot. Совпадение
        // с кэшем бит-в-бит → съём пропускается: дрейфа декомпозиции в покое нет.
        // written_fs == 0 → прошлый тик не писал (спавн/отсечён) — правка не снимается.
        glm::mat3 written_m{ 0.0f };
        glm::vec3 written_t{ 0.0f };
        float     written_fs = 0.0f;
    };

    // Дебаг-закладка (этап 2): запомнить текущую позицию камеры губки; её апдейтер раз в
    // секунду логирует смещение до закладки — живая проверка разности на любой глубине
    // (улетел-вернулся → offset ~0; нырнул глубже → ratio растёт как 3^Δd). Повторный вызов
    // перезаписывает. Вызывать с sim-потока (клавиша B в MainIterate).
    void MengerBookmarkHere();

    // Апдейтеры (по одному на фрактал; MainInit зовёт ОДИН — парой к CreateBufferData его буфера).
    void SetMengerFrameUpdater(EngineContext* ctx);
    void SetMandelbrotOrbitUpdater(EngineContext* ctx);

    // Ручной СДВИГ масштаба (удержание I/K): delta_levels — доля уровня за вызов, шаг *= 3^∓delta
    // (+ = «я мельче»/глубже, − = крупнее). У губки — сдвиг окна ±6 уровней вокруг авто-масштаба
    // (сам масштаб следует за расстоянием до стенки); у Мандельброта — half_h НАПРЯМУЮ, весь
    // диапазон (авто-слежения там нет, см. заголовок выше). Общий вызов для обоих фракталов
    // (активен один — второй свою половину состояния просто не читает). Вызывать с sim-потока.
    void FractalScaleStep(float delta_levels);

    // Push-константы фрактальных фонов (fragment слот 0 → b0, space3; раскладка = cbuffer
    // FractalParams обоих фрагментников). Данные инструкция строит САМА (время/итерации), а
    // состояние прохода игнорирует — поэтому регистрируется сырой формой CreatePushInstruction,
    // без типизированной обёртки: та разыменовала бы raw, который этим программам не нужен.
    struct alignas(16) FractalPushData {
        float    time      = 0.0f;   // губка: вращение света; Мандельброт: анимация палитры
        // Потолок шагов рэймарча (губка, over-relaxation ω=1.6) либо итераций пикселя
        // (Мандельброт — там пуш ставит MANDELBROT_ORBIT_MAX).
        uint32_t max_steps = 128;
        float    _pad0     = 0.0f;
        float    _pad1     = 0.0f;
    };
}
